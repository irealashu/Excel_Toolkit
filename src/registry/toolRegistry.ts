export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return TOOLS.find((tool) => tool.slug === slug || tool.id === slug);
}

export function getToolsByCategory(category: string): ToolDefinition[] {
  return TOOLS.filter((tool) => tool.category === category);
}

export function searchTools(query: string, categoryFilter?: string): ToolDefinition[] {
  const q = query.toLowerCase().trim();
  return TOOLS.filter((tool) => {
    if (categoryFilter && categoryFilter !== 'all' && tool.category !== categoryFilter) {
      return false;
    }
    if (!q) return true;
    const matchName = tool.name.toLowerCase().includes(q);
    const matchDesc = tool.description.toLowerCase().includes(q);
    const matchKeywords = tool.searchKeywords.some((k) => k.toLowerCase().includes(q));
    const matchFormats = tool.acceptedFormats.some((f) => f.toLowerCase().includes(q));
    return matchName || matchDesc || matchKeywords || matchFormats;
  });
}
